import { getTool } from './dist/tools/registry.js';
import * as fs from 'fs'; import * as os from 'os'; import * as path from 'path';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dbgreg-'));
fs.mkdirSync(path.join(dir, 'src'), { recursive: true });
fs.writeFileSync(path.join(dir, 'src', 'a.ts'), 'const a = 1;\nconst b = 2;\n');
process.env.GROQ_PROJECT_ROOT = dir;
const read = getTool('read_file');
const full = await read.run({ file_path: 'src/a.ts' });
console.log('FULL:', JSON.stringify(full).slice(0, 250));
const slice = await read.run({ file_path: 'src/a.ts', start_line: 2, end_line: 2 });
console.log('SLICE:', JSON.stringify(slice).slice(0, 250));
const write = getTool('write_file');
const w = await write.run({ file_path: 'new.md', content: '# Hi' });
console.log('WRITE:', JSON.stringify(w));
const edit = getTool('edit_file');
const e = await edit.run({ file_path: 'src/a.ts', old_text: 'const b = 2;', new_text: 'const b = 3;' });
console.log('EDIT:', JSON.stringify(e));
console.log('AFTER:', JSON.stringify(fs.readFileSync(path.join(dir,'src','a.ts'),'utf-8')));
fs.rmSync(dir, { recursive: true, force: true });
